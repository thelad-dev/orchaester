#!/usr/bin/env bash
# Count-in: 2 — 3 — 4
# Usage: bin/orch-setup.sh
set -euo pipefail
source "$(cd "$(dirname "$0")" && pwd)/orch-lib.sh"

say() { printf '%s\n' "$*"; }

say ""
say "  Orchäster"
say "  2…"
say "  3…"
say "  4."
say ""

# 2 — Arbeitsordner
default_work="${ORCH_WORK:-$HOME/src}"
say "2  Wo ist der lokale Arbeitsordner?"
say "   (Repos liegen darunter oder sind er. Crew-Leases werden Workspace-Unterordner orch/<id>.)"
printf "   [%s] " "$default_work"
if [[ -t 0 ]]; then
  read -r work || true
fi
work="${work:-$default_work}"
work="$(mkdir -p "$work" && cd "$work" && pwd)"

# 3 — Dirigent
say ""
say "3  Wer hebt den Taktstock?  grok  |  cursor"
printf "   [grok] "
if [[ -t 0 ]]; then
  read -r cond || true
fi
cond="${cond:-grok}"
case "$cond" in
  grok|cursor) ;;
  *) say "   unbekannt, nehme grok"; cond=grok ;;
esac

# 4 — schreiben und zeigen
say ""
say "4  Satz."

mkdir -p "$ORCH_HOME/config" "$ORCH_HOME/knowledge/crew"
printf '%s\n' "$work" > "$ORCH_HOME/config/work.root"
printf '%s\n' "$cond" > "$ORCH_HOME/config/conductor"

# seed workspaces from immediate git children of work root
python3 - "$work" "$ORCH_HOME/config/workspaces.toml" <<'PY'
import os, sys
root, dest = sys.argv[1], sys.argv[2]
rows = []
for name in sorted(os.listdir(root)):
    path = os.path.join(root, name)
    if name.startswith(".") or name == "orch":
        continue
    if os.path.isdir(os.path.join(path, ".git")) or os.path.isfile(os.path.join(path, ".git")):
        rows.append((name, path))
text = ["# generated by orch-setup.sh — edit freely", f"# work root: {root}", ""]
if not rows:
    text += [
        "[[workspace]]",
        'name = "example"',
        f'path = "{root}/example"',
        f'worktree_root = "{root}/example/orch"',
        "cursor = true",
        'remotes = ["origin"]',
        "",
    ]
for name, path in rows:
    text += [
        "[[workspace]]",
        f'name = "{name}"',
        f'path = "{path}"',
        f'worktree_root = "{path}/orch"',
        "cursor = true",
        'remotes = ["origin"]',
        "",
    ]
open(dest, "w").write("\n".join(text))
print(f"   workspaces: {len(rows)} unter {root}")
PY

# crew-knowledge pointer
ln -sfn "$ORCH_HOME/vendor/firstmate-crew-knowledge" \
  "$ORCH_HOME/knowledge/firstmate-crew-knowledge"

say "   work.root     $work"
say "   conductor     $cond"
say "   leases        <workspace>/orch/<task-id>"
say "   crew-knowledge knowledge/firstmate-crew-knowledge -> vendor/"
say ""
say "   Jetzt:  cd $ORCH_HOME && herdr"
if [[ "$cond" == "cursor" ]]; then
  say "           agent     # oder cursor-agent"
else
  say "           grok --trust"
fi
say ""
say "   Erster Takt: Lies AGENTS.md. 2-3-4. /ahoy."
